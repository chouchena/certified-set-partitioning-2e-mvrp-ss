r"""Area 2 -- small-instance floor-mapping / relaxation check (d794). READ-ONLY (builds tiny LPs).

Lemma teprelax says the floor model is a relaxation: every feasible street solution maps to a
floor-model point of equal cost, so LP^s(Delta) <= z^s. The grid-level evidence is already in hand
(LB <= OV on all 135 cells, gate G26). This adds the constructive detail on a tractable sub-instance:

  E1. the floor LP relaxes a REALIZABLE integer floor schedule -- solving the full master (all
      enumerated trips) as a mixed-integer program (lambda, z, rho, N integer) gives an integer
      optimum z_floor_IP, and LP^s <= z_floor_IP; the integer solution is a concrete floor schedule.
  E2. the trips the integer optimum selects PARTITION the customers (each customer covered exactly
      once by exactly one trip) -- the structure Lemma tepdecomp guarantees for a street solution.

Together with the ceil restriction (area 3: any integer floor schedule is realizable in continuous
time), this is the small-instance witness that the floor value lower-bounds a real street cost.
Reuses enum_price_check.enumerate_trips / full_master. No solver search beyond the tiny MIP.
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import verifier3 as V
from k_comparison import k_proximity
from tep_cg_bound import Master, default_delta
from enum_price_check import enumerate_trips, full_master


def check_cell(cell, size, n_cust):
    inst = V.load_instance(cell, size, k_proximity(size))
    customers = list(inst.customers)[:n_cust]
    delta = default_delta(inst)
    trips = enumerate_trips(Master(inst, delta, threads=1, primal=False, customers=customers))
    M, _ = full_master(inst, delta, customers, 0, trips)
    lp = M.m.ObjVal
    # E1: integer floor schedule -- make every structural variable integer and re-solve
    import gurobipy as gp
    for v in M.m.getVars():
        v.VType = gp.GRB.INTEGER          # an all-integer floor schedule (trips, transfers, waits, fleet)
    M.m.update()
    M.m.Params.OutputFlag = 0
    M.m.optimize()
    ip = M.m.ObjVal
    # E2: selected trip columns partition the customers
    sel = []
    for key, var in M.cols.items():
        if var.X > 0.5:
            sel.append((key[0], round(var.X)))   # (customer sequence, multiplicity)
    cover = {}
    for seq, mult in sel:
        for c in seq:
            cover[c] = cover.get(c, 0) + mult
    partition = all(cover.get(c, 0) == 1 for c in customers) and set(cover) <= set(customers)
    return {"cell": cell, "size": size, "n_cust": n_cust, "n_trips": len(trips),
            "floor_LP": round(lp, 6), "floor_IP": round(ip, 6),
            "LP_le_IP": lp <= ip + 1e-6, "trips_partition": bool(partition),
            "n_selected_trips": len(sel)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cells", default="C201,R201,RC201")
    ap.add_argument("--size", type=int, default=10)
    ap.add_argument("--n-cust", type=int, default=6)
    a = ap.parse_args()
    rows, problems = [], []
    for cell in a.cells.split(","):
        r = check_cell(cell, a.size, a.n_cust)
        rows.append(r)
        if not r["LP_le_IP"]:
            problems.append("%s n%d: floor LP %.6f > floor IP %.6f" % (cell, a.size, r["floor_LP"], r["floor_IP"]))
        if not r["trips_partition"]:
            problems.append("%s n%d: selected trips do not partition the customers" % (cell, a.size))
        print("  %-5s trips=%d  floor LP=%.4f <= floor IP=%.4f : %s | partition: %s"
              % (cell, r["n_trips"], r["floor_LP"], r["floor_IP"],
                 "PASS" if r["LP_le_IP"] else "FAIL", "PASS" if r["trips_partition"] else "FAIL"))
    lines = ["# Area 2 -- small-instance floor-mapping / relaxation check", "",
             "> Evidence for the \"Relaxation validity\" acceptance row (d794). Generated by",
             "> `analysis/floor_map_check.py`. Grid-level relaxation (LB <= OV on all 135 cells) is",
             "> enforced by gate G26 and cert_audit; this is the constructive small-instance witness.", "",
             "| cell | size | \\|C\\| | trips | floor LP | floor IP | LP <= IP | trips partition |",
             "|------|------|-----|-------|----------|----------|----------|-----------------|"]
    for r in rows:
        lines.append("| %s | %d | %d | %d | %.4f | %.4f | %s | %s |"
                     % (r["cell"], r["size"], r["n_cust"], r["n_trips"], r["floor_LP"], r["floor_IP"],
                        "yes" if r["LP_le_IP"] else "**NO**", "yes" if r["trips_partition"] else "**NO**"))
    lines += ["", ("**Floor LP relaxes a realizable integer floor schedule, and the selected trips "
                   "partition the customers, on every sampled cell.**" if not problems else "**VIOLATIONS:**")]
    for p in problems:
        lines.append("- " + p)
    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       "validation", "AREA2_FLOOR_MAPPING.md")
    open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("wrote %s (%d cells, %d problem(s))" % (os.path.relpath(out, os.getcwd()), len(rows), len(problems)))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
