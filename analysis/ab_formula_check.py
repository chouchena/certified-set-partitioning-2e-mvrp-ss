r"""Area 7 -- arithmetic-bound (AB4) formula, components, and reproduction (d795).

The reported arithmetic bound is crossfeed.fullset_bound (NOT ab4_grid, which computes a different,
stale quantity). Its formula, with every component a separately valid lower bound so the combination
stays valid:

    AB4 = penaltyCars * V_LB  +  travelcoststreet * Dist_LB  +  water

    Dist_LB = max( d_ap, d_mst, d_ft )            -- three independently valid street-travel bounds
        d_ap  assignment relaxation (one distinct successor per customer; Fischetti ATSP,
              Toth-Vigo assignment)
        d_mst minimum spanning tree (Held-Karp)
        d_ft  forced-terminal LP: trips must terminate at a satellite >= trips_lb times, adding
              terminal arcs the assignment escape omits (Toth-Vigo depot-duplication lineage)
    V_LB    = max( routes_lb_time, ceil(work/H), clique )   -- street fleet lower bound
        routes_lb_time / work  workload-over-horizon (service + Dist_LB-as-time + trips_lb*U)
        clique  time-window incompatibility clique (Kohl 2-path lineage), GATED on the triangle
              inequality (dropped where D is non-metric, so a false clique cannot inflate V_LB)
    trips_lb  bin-packing trip count (Martello), feeds d_ft and work
    water     K's full-demand water bound (vessel travel + fleet), recalled, not ours

This script reproduces fullset_bound per cell at the reported proximity and ASSERTS the reproduced
total equals the frozen-grid ab4 (reproducible component values), then tabulates the components.
Deterministic arithmetic, no solver search. Writes validation/AREA7_ARITHMETIC_BOUND.md.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "analysis"))
from build_instance import build
from crossfeed.fullset_bound import fullset_bound
from k_comparison import k_proximity
import recap_grid_vs_k as R

SIZES = (10, 20, 30, 50, 100)
TOL = 1e-2


def frozen_ab4(cell, size):
    p = os.path.join(ROOT, "runs", "oracle", "tep_solve_frzdual2_%s_n%d.json" % (cell, size))
    if not os.path.exists(p):
        return None
    r = json.load(open(p))["rows"][0]
    return r.get("ab4")


def main():
    rows, problems = [], []
    for size in SIZES:
        prox = k_proximity(size)
        for cell in R.CELLS:
            fa = frozen_ab4(cell, size)
            if fa is None:
                continue
            p = build(cell, size, wls=0.1, tau="formula", proximity=prox, time_limit=60)
            b, parts = fullset_bound(p)
            match = abs(b - float(fa)) < TOL * max(1.0, abs(float(fa)))
            if not match:
                problems.append("%s n%d: reproduced AB4 %.4f != frozen %.4f" % (cell, size, b, float(fa)))
            rows.append({"cell": cell, "size": size, "ab4": round(b, 3), "frozen": round(float(fa), 3),
                         "match": match, **parts})

    # carriers: the cells where AB4 is the reported bound (ab4 > lb_composed) -- all n10 per cert_audit
    nj = json.load(open(os.path.join(ROOT, "paper", "numbers.json")))
    reg_ab = int(nj["portfolio"]["value"]["ab-carries-cells"])

    lines = ["# Area 7 -- arithmetic bound (AB4): formula, components, reproduction", "",
             "> Evidence for the \"Arithmetic bound\" acceptance row (d795). The reported bound is",
             "> `crossfeed.fullset_bound`. Generated by `analysis/ab_formula_check.py`, which reproduces it",
             "> per cell at the reported proximity and checks the total against the frozen-grid `ab4`.", "",
             "## Formula", "",
             "```", "AB4 = penaltyCars*V_LB + travelcoststreet*Dist_LB + water",
             "Dist_LB = max(d_ap [assignment], d_mst [MST/Held-Karp], d_ft [forced-terminal])",
             "V_LB    = max(routes_lb_time, ceil(work/H), clique)   # clique gated on triangle ineq.",
             "trips_lb = bin-packing trip count (feeds d_ft and work)", "```", "",
             "Each of d_ap/d_mst/d_ft is an independently valid street-travel lower bound, so their max",
             "is valid; each term of V_LB is a valid fleet lower bound, so their max is valid; water is",
             "the predecessors' full-demand bound. The reported LB is max(LP+water, AB4) per cell.", ""]
    # per-size winner / clique summary
    lines += ["## Component summary by size", "",
              "| size | cells | reproduced == frozen | Dist winner (AP/MST/FORCED) | clique used |",
              "|------|-------|----------------------|------------------------------|-------------|"]
    for size in SIZES:
        rs = [r for r in rows if r["size"] == size]
        if not rs:
            continue
        wins = {}
        for r in rs:
            wins[r["dist_winner"]] = wins.get(r["dist_winner"], 0) + 1
        clq = sum(1 for r in rs if r.get("clique_used"))
        nm = sum(1 for r in rs if r["match"])
        lines.append("| %d | %d | %d/%d | %s | %d |"
                     % (size, len(rs), nm, len(rs),
                        ", ".join("%s:%d" % (k, v) for k, v in sorted(wins.items())), clq))
    # full component detail for the AB-carrier cells (all n10)
    carriers = [r for r in rows if r["size"] == 10]  # cert_audit: all 11 AB-carriers are n10
    lines += ["", "## Per-cell components, $|C| = 10$ (the AB4 carriers live here)", "",
              "| cell | V_LB | routes_time | clique | d_ap | d_mst | d_ft | Dist_LB | fleet | travel | water | AB4 |",
              "|------|------|-------------|--------|------|-------|------|---------|-------|--------|-------|-----|"]
    for r in sorted(carriers, key=lambda x: x["cell"]):
        lines.append("| %s | %s | %s | %s | %.1f | %.1f | %.1f | %.1f | %.1f | %.1f | %.1f | %.2f |"
                     % (r["cell"], r["V_LB"], r["routes_lb_time"], r["clique"],
                        r["dist_ap"], r["dist_mst"], r["dist_forced"], r["dist_raw"],
                        r["fleet_term"], r["travel_term"], r["water"], r["ab4"]))
    lines += ["", "## Summary", "",
              "- cells reproduced: **%d**; reproduced AB4 == frozen-grid ab4 on **%d**"
              % (len(rows), sum(1 for r in rows if r["match"])),
              "- AB4 carries the reported bound on **%d** cells (registered portfolio.ab-carries-cells)"
              % reg_ab,
              "", ("**Every frozen-grid AB4 is reproduced by `fullset_bound` and decomposes into the "
                   "documented components.**" if not problems else "**VIOLATIONS:**")]
    for p_ in problems:
        lines.append("- " + p_)
    out = os.path.join(ROOT, "validation", "AREA7_ARITHMETIC_BOUND.md")
    open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("wrote %s (%d cells, %d reproduced, %d problem(s))"
          % (os.path.relpath(out, os.getcwd()), len(rows), sum(1 for r in rows if r["match"]), len(problems)))
    for p_ in problems[:15]:
        print("  PROBLEM:", p_)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
